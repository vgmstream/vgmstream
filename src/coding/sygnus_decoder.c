/* Bandai Namco's Sygnus sound lib ADPCM (from exes).
 * Suspiciously similar to PtADPCM but float-based and using more indexes, possibly there is some dev link.
 * Info: https://github.com/Nenkai/010GameTemplates/blob/master/Bandai%20Namco/SOL-AVES/SolAvesSygnus_SoundStream.bt */
void decode_sygnus(VGMSTREAMCHANNEL* stream, short* outbuf, int channelspacing, int32_t first_sample, int32_t samples_to_do, size_t frame_size) {
    uint8_t frame[0x108] = {0};
    off_t frame_offset;
    int sample_count = 0, samples_done = 0;
    int index, nibble;
    float step;
    float hist1, hist2;

    /* external interleave (variable size), mono */
    size_t bytes_per_frame = frame_size;
    size_t samples_per_frame = 2 + (frame_size - 0x09) * 2;
    int frames_in = first_sample / samples_per_frame;
    //first_sample = first_sample % samples_per_frame;

    /* parse frame header */
    frame_offset = stream->offset + bytes_per_frame * frames_in;
    read_streamfile(frame, frame_offset, bytes_per_frame, stream->streamfile); /* ignore EOF errors */
    hist2 = get_f32le(frame + 0x00); // +-1.0 based
    hist1 = get_f32le(frame + 0x04);
    index = frame[0x08];

    VGM_ASSERT_ONCE(index > 31, "SYGNUS: incorrect index at %x\n", (uint32_t)frame_offset);
    if (index > 31)
        index = 31;

    /* write header samples (needed) */
    if (sample_count >= first_sample && samples_done < samples_to_do) {
        outbuf[samples_done * channelspacing] = hist2 * 32767.0f;
        samples_done++;
    }
    sample_count++;
    if (sample_count >= first_sample && samples_done < samples_to_do) {
        outbuf[samples_done * channelspacing] = hist1 * 32767.0f;
        samples_done++;
    }
    sample_count++;

    /* decode nibbles */
    for (int i = 0; i < samples_per_frame - 2; i++) {
        uint8_t nibbles = frame[0x09 + i/2];
        float sample;

        nibble = !(i&1) ? /* low nibble first */
                (nibbles >> 0) & 0xF :
                (nibbles >> 4) & 0xF;

        step  = sygnus_table[index][nibble].delta;
        index = sygnus_table[index][nibble].index;
        sample = step - (hist2 - 2.0f * hist1);

        if (sample_count >= first_sample && samples_done < samples_to_do) {
            outbuf[samples_done * channelspacing] = clamp16(sample * 32767.0f); //TODO: OG outputs +-1.0 floats
            samples_done++;
        }
        sample_count++;

        hist2 = hist1;
        hist1 = sample;
    }

    //stream->adpcm_history1_32 = hist1;
    //stream->adpcm_history2_32 = hist2;
}
